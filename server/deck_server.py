#!/usr/bin/env python3
"""Runs the upstream DCSS webtiles server as a private, single-player local server.

The app's files are read-only (inside the AppImage), so this script generates a server
config pointing every writable path (saves, rc files, morgues, the user database, sockets)
into --data-dir, makes sure the local player account exists, and then starts the upstream
server unchanged. It only listens on 127.0.0.1 and logs the player in automatically.

Usage:
  deck_server.py --crawl-dir DIR --data-dir DIR --port N [--user NAME]

--crawl-dir is the crawl-ref/source directory of a `make WEBTILES=y` build: it holds
the `crawl` binary, `dat/` and `webserver/`.
"""

import argparse
import importlib.util
import os
import re
import secrets
import sys

GAME_ID = "dcss-deck"

CONFIG_TEMPLATE = '''\
# Generated by DCSS Deck on every start. Edits will be overwritten.
import collections
import logging

dgl_mode = True
autologin = {user!r}
bind_nonsecure = True
bind_address = "127.0.0.1"
bind_port = {port}
ssl_options = None
logging_config = {{"level": logging.INFO, "format": "%(asctime)s %(levelname)s: %(message)s"}}
password_db = {data!r} + "/passwd.db3"
settings_db = {data!r} + "/user_settings.db3"
static_path = {crawl!r} + "/webserver/static"
template_path = {crawl!r} + "/webserver/templates/"
server_socket_path = None
server_id = "dcss-deck"
game_data_no_cache = False
watch_socket_dirs = False
use_game_yaml = False
dgl_status_file = {data!r} + "/rcs/status"
init_player_program = {init!r}
new_accounts_disabled = True
max_connections = 4
pidfile = None
daemon = False
hup_reloads_config = False
lobby_url = None
player_url = None
uid = None
gid = None
umask = 0o077
chroot = None

games = collections.OrderedDict([
    ({game_id!r}, dict(
        name = "Play DCSS %v",
        version = {version!r},
        crawl_binary = {crawl!r} + "/crawl",
        cwd = {crawl!r},
        rcfile_path = {data!r} + "/rcs/",
        macro_path = {data!r} + "/rcs/",
        morgue_path = {data!r} + "/morgue/%n",
        inprogress_path = {data!r} + "/rcs/running",
        ttyrec_path = {data!r} + "/ttyrecs/%n",
        socket_path = {sockets!r},
        dir_path = {data!r} + "/saves",
        client_path = {crawl!r} + "/webserver/game_data/",
        morgue_url = None,
        show_save_info = True,
        allowed_with_hold = True,
        env = {env!r},
    )),
])
'''


def crawl_version(crawl_dir: str) -> str:
    """Reads the version from the build's generated build.h, e.g. "0.34.1"."""
    try:
        with open(os.path.join(crawl_dir, "build.h"), encoding="utf-8") as f:
            m = re.search(r'CRAWL_VERSION_SHORT\s+"([^"]+)"', f.read())
            if m:
                return m.group(1)
    except OSError:
        pass
    return "local"


def crawl_env(crawl_dir: str) -> dict:
    """Bundled builds ship the libraries crawl links (ncurses) in <crawl>/lib."""
    lib = os.path.join(crawl_dir, "lib")
    if not os.path.isdir(lib):
        return {}
    existing = os.environ.get("LD_LIBRARY_PATH")
    return {"LD_LIBRARY_PATH": lib + (":" + existing if existing else "")}


def socket_dir() -> str:
    """A short, private directory for the server <-> crawl sockets."""
    runtime = os.environ.get("XDG_RUNTIME_DIR")
    if runtime and os.path.isdir(runtime):
        return os.path.join(runtime, "dcss-deck")
    return f"/tmp/dcss-deck-{os.getuid()}"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--crawl-dir", required=True)
    parser.add_argument("--data-dir", required=True)
    parser.add_argument("--port", type=int, required=True)
    parser.add_argument("--user", default="Player")
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Za-z0-9]{1,20}", args.user):
        sys.exit("--user must be 1-20 letters or digits")

    crawl = os.path.abspath(args.crawl_dir)
    data = os.path.abspath(args.data_dir)
    here = os.path.dirname(os.path.abspath(__file__))
    for sub in ("rcs/running", "morgue", "ttyrecs", "saves/morgue"):
        os.makedirs(os.path.join(data, sub), exist_ok=True)

    sockets = socket_dir()
    os.makedirs(sockets, mode=0o700, exist_ok=True)
    # crawl names its socket "<sockets>/<user>:<timestamp>.sock"; Unix socket paths are
    # limited to 107 bytes and crawl aborts on longer ones.
    if len(f"{sockets}/{args.user}:20261231-235959.sock") > 100:
        sys.exit(f"socket directory path is too long: {sockets}")

    # The init script reads these to set up the player's rc file and folders.
    os.environ["DCSS_DECK_DATA"] = data
    os.environ["DCSS_DECK_DEFAULT_RC"] = os.path.join(here, "deck-default.rc")

    config_path = os.path.join(data, "deck_config.py")
    with open(config_path, "w", encoding="utf-8") as f:
        f.write(CONFIG_TEMPLATE.format(
            user=args.user, port=args.port, data=data, crawl=crawl, sockets=sockets,
            env=crawl_env(crawl),
            init=os.path.join(here, "init-player.sh"),
            game_id=GAME_ID, version=crawl_version(crawl),
        ))

    sys.path.insert(0, os.path.join(crawl, "webserver"))
    import webtiles.config
    import webtiles.server
    from webtiles import userdb

    sys.dont_write_bytecode = True  # keep __pycache__ out of the data dir
    spec = importlib.util.spec_from_file_location("deck_config", config_path)
    module = importlib.util.module_from_spec(spec)
    sys.modules["deck_config"] = module
    spec.loader.exec_module(module)
    webtiles.config.init_config_from_module(module)
    webtiles.config.server_path = os.path.join(crawl, "webserver")

    # autologin needs the account to exist. Nobody ever types this password.
    userdb.init_db_connections(quiet=True)
    if userdb.get_user_info(args.user) is None:
        webtiles.config.set("new_accounts_disabled", False)
        err = userdb.register_user(args.user, secrets.token_urlsafe(24), "")
        webtiles.config.set("new_accounts_disabled", True)
        if err:
            sys.exit(f"could not create local player: {err}")

    # Lets the app know the server is ready (see src/main/local-server.ts).
    print(f"DCSS_DECK_READY game={GAME_ID} port={args.port} version={crawl_version(crawl)}", flush=True)
    sys.argv = [sys.argv[0], "--no-daemon", "--no-pidfile", "--logfile", "-"]
    webtiles.server.run()


if __name__ == "__main__":
    main()
